import { createHash, randomBytes } from 'node:crypto';

// CA-1（docs/APP-NATIVE.md §3.1）：App Bearer Token——明文只出现在签发响应里，库中只存 sha256 哈希。
export const API_TOKENS_DDL = `create table if not exists api_tokens (
  id           bigint generated by default as identity primary key,
  user_id      integer not null references users(id) on delete cascade,
  token_hash   text not null unique,
  name         text,
  created_at   timestamptz not null default now(),
  last_used_at timestamptz,
  expires_at   timestamptz not null,
  revoked_at   timestamptz
);
create index if not exists idx_api_tokens_user on api_tokens (user_id);
`;

export function apiTokenHash(token) {
  return createHash('sha256').update(String(token)).digest('hex');
}

/**
 * 签发 App Token：32 字节随机 base64url → 只存哈希。
 * days 由调用方定（默认 30 记住我 / 7 普通）；返回 { token, expiresAt }。
 */
export async function insertApiToken(q, { userId, name = null, days = 7 }) {
  const token = randomBytes(32).toString('base64url');
  await q(
    `insert into api_tokens (user_id, token_hash, name, expires_at) values ($1, $2, $3, now() + ($4 || ' days')::interval)`,
    [userId, apiTokenHash(token), name, String(days)],
  );
  await q('update users set last_login_at = now() where id = $1', [userId]);
  const expiresAt = new Date(Date.now() + days * 86400_000).toISOString();
  return { token, expiresAt };
}

/**
 * 用 token 换用户：校验哈希 + 未过期 + 未撤销 + 用户未禁用（与 userBySession 同口径）。
 * 返回 { id, username, role, must_change_password } 或 null。
 */
export async function userByApiToken(q, token) {
  if (!token) return null;
  const r = await q(
    `select u.id, u.username, u.role, u.disabled, u.must_change_password
       from api_tokens t join users u on u.id = t.user_id
      where t.token_hash = $1 and t.expires_at > now() and t.revoked_at is null and not u.disabled`,
    [apiTokenHash(token)],
  );
  const row = r.rows[0];
  return row ? { id: row.id, username: row.username, role: row.role, must_change_password: Boolean(row.must_change_password) } : null;
}

/** 撤销一个 token（退出登录）。返回行数。 */
export async function revokeApiToken(q, token) {
  if (!token) return 0;
  const r = await q('update api_tokens set revoked_at = now() where token_hash = $1 and revoked_at is null', [apiTokenHash(token)]);
  return r.rowCount ?? 0;
}

/** 节流写最近使用（server 层 5 分钟内存节流，这里只负责写）。 */
export async function touchApiToken(q, token) {
  if (!token) return;
  await q('update api_tokens set last_used_at = now() where token_hash = $1', [apiTokenHash(token)]);
}
