  const params = [];
  if (displayName !== undefined) {
    params.push(displayName);
    sets.push(`display_name = $${params.length}`);
  }
  if (role !== undefined) {
    params.push(role);
    sets.push(`role = $${params.length}`);
  }
  if (disabled !== undefined) {
    params.push(Boolean(disabled));
    sets.push(`disabled = $${params.length}`);
  }
